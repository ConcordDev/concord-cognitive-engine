#!/usr/bin/env python3
"""NEC2 kernel (nec2c) — SXE-17.

Speaks the SXE-00 kernel protocol: {"op", "request"} JSON on stdin,
one result JSON on stdout. Health case (the plan's): the half-wave
dipole's input impedance vs the closed-form reference 73 + j42.5
ohm (the standard thin-wire half-wave dipole value). The deck is
generated in-kernel: a centre-fed wire of length lambda/2 at the
request frequency, radius lambda/1000, 21 segments; nec2c runs as
a separate process (public-domain code, nothing imported) and the
kernel parses the ANTENNA INPUT PARAMETERS block of its output.

Ops:
  health / dipole-impedance — request {frequencyMHz} (default 300)
    -> {resistanceOhm, reactanceOhm, expectedResistanceOhm,
        expectedReactanceOhm, absErrorR, absErrorX, converged}.

Bands: |R - 73| <= 10 ohm, |X - 42.5| <= 15 ohm (NEC2 thin-wire
results move a few ohms with segmentation and radius; the bands
cover the converged range without letting a wrong deck pass).

No nec2c binary on PATH is a provisioning defect: exit 3.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile


def fail(code, message):
    print(message, file=sys.stderr)
    sys.exit(code)


C_M_S = 299792458.0
EXPECTED_R, EXPECTED_X = 73.0, 42.5
BAND_R, BAND_X = 10.0, 15.0


def deck(freq_mhz):
    lam = C_M_S / (freq_mhz * 1e6)
    half = lam / 4.0  # each arm is lambda/4; total length lambda/2
    radius = lam / 1000.0
    return (
        "CM half-wave dipole, generated by the ConKay nec2c kernel\n"
        "CE SXE-17 health case\n"
        "GW 1 21 0 0 %.6f 0 0 %.6f %.6f\n"
        "GE 0\n"
        "EX 0 1 11 0 1 0\n"
        "FR 0 1 0 0 %.4f 0\n"
        "XQ\n"
        "EN\n" % (-half, half, radius, freq_mhz))


def run_dipole(freq_mhz):
    exe = shutil.which("nec2c")
    if not exe:
        fail(3, "nec2c executable not found on PATH - the nec2c "
                "driver env is not provisioned")
    with tempfile.TemporaryDirectory(prefix="conkay-nec2c-") as td:
        deck_path = os.path.join(td, "dipole.nec")
        out_path = os.path.join(td, "dipole.out")
        with open(deck_path, "w") as fh:
            fh.write(deck(freq_mhz))
        proc = subprocess.run([exe, "-i", deck_path, "-o", out_path],
                              capture_output=True, text=True, timeout=120)
        if proc.returncode != 0 or not os.path.exists(out_path):
            fail(6, "nec2c run failed (rc=%s): %s"
                    % (proc.returncode, (proc.stderr or "")[:200]))
        text = open(out_path).read()
    # ANTENNA INPUT PARAMETERS block: a data line carrying
    # VOLTAGE / CURRENT / IMPEDANCE R / IMPEDANCE X after the header.
    m = re.search(r"ANTENNA INPUT PARAMETERS(.*?)"
                  r"\n\s*\d+\s+\d+\s+[-0-9.E+]+ [-0-9.E+]+\s+"
                  r"([-0-9.E+]+)\s+([-0-9.E+]+)", text, re.S)
    if not m:
        fail(6, "nec2c output carried no antenna input impedance")
    r_ohm, x_ohm = float(m.group(1)), float(m.group(2))
    err_r, err_x = abs(r_ohm - EXPECTED_R), abs(x_ohm - EXPECTED_X)
    ok = err_r <= BAND_R and err_x <= BAND_X
    return {"resistanceOhm": r_ohm, "reactanceOhm": x_ohm,
            "expectedResistanceOhm": EXPECTED_R,
            "expectedReactanceOhm": EXPECTED_X,
            "absErrorR": err_r, "absErrorX": err_x, "converged": ok}


def main():
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        fail(2, "kernel input was not valid JSON")
    op = payload.get("op")
    request = payload.get("request") or {}
    if op in ("health", "dipole-impedance"):
        freq = request.get("frequencyMHz", 300)
        if not isinstance(freq, (int, float)) or not (30 <= freq <= 3000):
            fail(2, "frequencyMHz must be a number in [30, 3000], "
                    "got %r" % (freq,))
        result = run_dipole(float(freq))
    else:
        fail(2, "unknown op %r" % (op,))
    print(json.dumps(result))


if __name__ == "__main__":
    main()
